// Stage 2: builds the SDK's path-word vocabulary from .cache/segments.json
// (src/fetch.mjs), seed.txt and names.txt (src/names.mjs), and writes
// packages/shared/src/vocabulary-words.ts plus report.md.
//
// A word is kept when it appears as a literal path segment, or as a part of
// one (`payment-methods`, `line_items`, `bulkUpdate`), in at least MIN_APIS
// different APIs of the directory. Seed words are always kept. Names
// (names.txt) are dropped unless they are seed words or appear in at least
// COMMON_PROVIDERS different providers' APIs (an ordinary API word such as
// `mark` or `rose`); those collisions are listed in report.md.
//   node src/build.mjs [--min-apis 5] [--common-providers 5]
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const opt = (name, dflt) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? Number(process.argv[i + 1]) : dflt;
};
const MIN_APIS = opt('min-apis', 5);
const COMMON_PROVIDERS = opt('common-providers', 5);

const words = (file) =>
  readFileSync(path.join(root, file), 'utf8')
    .split('\n')
    .filter((l) => !l.startsWith('#'))
    .flatMap((l) => l.trim().split(/\s+/))
    .filter(Boolean)
    .map((w) => w.toLowerCase());

/**
 * Same split as the SDK (`pathWords` in packages/shared/src/vocabulary.ts):
 * separators and camelCase boundaries, lower-cased.
 */
function parts(segment) {
  return segment
    .replace(/([a-z\d])([A-Z])/g, '$1 $2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
    .toLowerCase()
    .split(/[^a-z\d]+/)
    .filter(Boolean);
}

/** Word-like: starts with a letter, at most 2 digits, 2–24 characters. */
const RE_WORD = /^[a-z][a-z\d]{1,23}$/;
const wordLike = (w) => RE_WORD.test(w) && (w.match(/\d/g)?.length ?? 0) <= 2;

const segments = JSON.parse(readFileSync(path.join(root, '.cache', 'segments.json'), 'utf8'));
const apis = new Map(); // word → Set of API keys
const providers = new Map(); // word → Set of providers
for (const [key, segs] of Object.entries(segments)) {
  const provider = key.split(':')[0];
  const seen = new Set();
  for (const seg of segs) for (const w of parts(seg)) if (wordLike(w)) seen.add(w);
  for (const w of seen) {
    if (!apis.has(w)) {
      apis.set(w, new Set());
      providers.set(w, new Set());
    }
    apis.get(w).add(key);
    providers.get(w).add(provider);
  }
}

const seed = new Set(words('seed.txt'));
const names = new Set(words('names.txt'));
const mined = [...apis].filter(([, s]) => s.size >= MIN_APIS).map(([w]) => w);
const kept = new Set(seed);
const collisions = [];
const droppedNames = [];
for (const w of mined) {
  if (names.has(w) && !seed.has(w)) {
    if ((providers.get(w)?.size ?? 0) >= COMMON_PROVIDERS) collisions.push(w);
    else {
      droppedNames.push(w);
      continue;
    }
  }
  kept.add(w);
}
for (const w of seed) if (names.has(w)) collisions.push(w);
const sorted = [...kept].sort();
const body = sorted.join(' ');

writeFileSync(
  path.join(root, '..', '..', 'packages', 'shared', 'src', 'vocabulary-words.ts'),
  `// Generated by tools/vocabulary (src/build.mjs); do not edit by hand.
// Path words used by at least ${MIN_APIS} APIs of the APIs.guru OpenAPI directory (CC0),
// plus tools/vocabulary/seed.txt, minus personal names (tools/vocabulary/names.txt).
// ${sorted.length} words.
export const VOCABULARY_WORDS =
  '${body}';
`,
);

const uniqCollisions = [...new Set(collisions)].sort();
writeFileSync(
  path.join(root, 'report.md'),
  `# Vocabulary build report

Generated by \`src/build.mjs\` (min APIs ${MIN_APIS}, names kept when in the seed list or used by ≥ ${COMMON_PROVIDERS} providers).

- APIs scanned: ${Object.keys(segments).length} (${new Set(Object.keys(segments).map((k) => k.split(':')[0])).size} providers)
- Distinct word-like parts: ${apis.size}
- Mined (≥ ${MIN_APIS} APIs): ${mined.length}
- Seed words: ${seed.size}
- Names dropped: ${droppedNames.length}
- Vocabulary: ${sorted.length} words, ${Buffer.byteLength(body)} bytes

## Names kept because they are also ordinary API words (residual risk)

${uniqCollisions.map((w) => `\`${w}\` (${providers.get(w)?.size ?? 0} providers${seed.has(w) ? ', seed' : ''})`).join(', ')}

## Names dropped

${droppedNames.sort().join(', ')}
`,
);
console.log(
  `vocabulary: ${sorted.length} words, ${Buffer.byteLength(body)} bytes; mined ${mined.length}, names dropped ${droppedNames.length}, kept collisions ${uniqCollisions.length}`,
);
