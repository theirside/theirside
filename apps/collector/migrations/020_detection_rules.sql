-- Packed histogram addition, for upserts and merges of one row. Sums over many rows unnest the
-- arrays and group by bucket instead (storage/columns.ts summedQuery): an aggregate function's
-- state array is copied on every row, ~100× slower for a 7-day baseline.
CREATE FUNCTION theirside_hist_add(a integer[], b integer[]) RETURNS integer[]
LANGUAGE plpgsql IMMUTABLE PARALLEL SAFE AS $$
DECLARE
  na integer := coalesce(cardinality(a), 0);
  nb integer := coalesce(cardinality(b), 0);
  lo integer; hi integer; r integer[]; i integer;
BEGIN
  IF na < 2 THEN RETURN CASE WHEN nb < 2 THEN NULL ELSE b END; END IF;
  IF nb < 2 THEN RETURN a; END IF;
  lo := least(a[1], b[1]);
  hi := greatest(a[1] + na - 2, b[1] + nb - 2);
  r := array_fill(0, ARRAY[hi - lo + 2]);
  r[1] := lo;
  FOR i IN 2..na LOOP r[a[1] - lo + i] := r[a[1] - lo + i] + a[i]; END LOOP;
  FOR i IN 2..nb LOOP r[b[1] - lo + i] := r[b[1] - lo + i] + b[i]; END LOOP;
  RETURN r;
END $$;

